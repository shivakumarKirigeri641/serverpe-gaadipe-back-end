-- 092_rtos.sql — every RTO in India, by code (user, 2026-10-01).
-- Loaded once from the state-wise lists on Wikipedia ("List of Regional Transport
-- Office districts in India", 2026-10-01), cleaned: vehicle-category letters
-- and never-allocated codes left out. Telangana is kept as TS, the code the Where
-- page uses; TG plates fold into it. vahan_name is the office name the Government
-- record gives for vehicles we look up — learned as we go, and shown first.

CREATE TABLE IF NOT EXISTS rtos (
  code        text PRIMARY KEY,           -- KA01, DL01, TS07
  state_code  text NOT NULL,
  office      text,
  district    text,
  notes       text,
  vahan_name  text,                       -- as the Government record writes it
  vahan_at    timestamptz,
  source      text NOT NULL DEFAULT 'list',  -- list | vahan (a code only the record knew)
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_rtos_state ON rtos (state_code);

